-- Execute este script no SQL Editor do projeto Supabase.
-- A chave secreta do Supabase deve ficar somente nas variáveis do servidor.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null,
  password_hash text,
  password_legacy text,
  created_at timestamptz not null default now()
);

-- Também prepara uma tabela users mais antiga, criada pela versão que salvava
-- a senha em uma coluna chamada password.
alter table public.users add column if not exists password_hash text;
alter table public.users add column if not exists password_legacy text;

do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'users'
      and column_name = 'password'
  ) then
    execute 'update public.users set password_legacy = password where password_legacy is null';
    alter table public.users drop column password;
  end if;
end
$$;

create unique index if not exists users_email_lower_unique
  on public.users (lower(email));

alter table public.users enable row level security;

grant usage on schema public to service_role;
grant select, insert, update on table public.users to service_role;
grant usage, select on all sequences in schema public to service_role;

